DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'monthly_cycle_status') THEN
    CREATE TYPE public.monthly_cycle_status AS ENUM (
      'open',
      'locked',
      'prep',
      'calculation',
      'verification',
      'approval',
      'distribution',
      'completed',
      'reporting'
    );
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.monthly_cycles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_key text NOT NULL UNIQUE,
  year smallint NOT NULL,
  month smallint NOT NULL,
  period_start date NOT NULL,
  period_end date NOT NULL,
  status public.monthly_cycle_status NOT NULL DEFAULT 'open',
  opened_at timestamp with time zone NOT NULL DEFAULT now(),
  locked_at timestamp with time zone,
  prep_started_at timestamp with time zone,
  calculation_started_at timestamp with time zone,
  verification_started_at timestamp with time zone,
  approval_started_at timestamp with time zone,
  distribution_started_at timestamp with time zone,
  completed_at timestamp with time zone,
  reporting_published_at timestamp with time zone,
  operator_note text,
  status_note text,
  created_by_user_id uuid REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  updated_by_user_id uuid REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT monthly_cycles_cycle_key_format_check CHECK (cycle_key ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  CONSTRAINT monthly_cycles_year_month_check CHECK (
    year = split_part(cycle_key, '-', 1)::smallint
    AND month = split_part(cycle_key, '-', 2)::smallint
  ),
  CONSTRAINT monthly_cycles_month_bounds_check CHECK (
    month BETWEEN 1 AND 12
    AND period_start = make_date(year::integer, month::integer, 1)
    AND period_end = (make_date(year::integer, month::integer, 1) + interval '1 month - 1 day')::date
  ),
  CONSTRAINT monthly_cycles_year_month_key UNIQUE (year, month)
);

CREATE INDEX IF NOT EXISTS idx_monthly_cycles_status
ON public.monthly_cycles (status, period_start DESC);

CREATE INDEX IF NOT EXISTS idx_monthly_cycles_period
ON public.monthly_cycles (period_start DESC);

