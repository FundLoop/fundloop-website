WITH cycle_sources AS (
  SELECT to_char(period_end, 'YYYY-MM') AS cycle_key
  FROM public.payments
  WHERE period_end IS NOT NULL

  UNION
  SELECT to_char(submitted_at, 'YYYY-MM') AS cycle_key
  FROM public.onchain_payment_submissions
  WHERE submitted_at IS NOT NULL

  UNION
  SELECT month AS cycle_key
  FROM public.zkas_identity_artifacts
  WHERE month ~ '^\d{4}-(0[1-9]|1[0-2])$'

  UNION
  SELECT month AS cycle_key
  FROM public.zkas_datasets
  WHERE month ~ '^\d{4}-(0[1-9]|1[0-2])$'

  UNION
  SELECT month AS cycle_key
  FROM public.zkas_runs
  WHERE month ~ '^\d{4}-(0[1-9]|1[0-2])$'

  UNION
  SELECT format('%s-%s', year, lpad(month::text, 2, '0')) AS cycle_key
  FROM public.project_stats_monthly
  WHERE year IS NOT NULL AND month BETWEEN 1 AND 12
)
INSERT INTO public.monthly_cycles (cycle_key, year, month, period_start, period_end)
SELECT
  cycle_key,
  split_part(cycle_key, '-', 1)::smallint AS year,
  split_part(cycle_key, '-', 2)::smallint AS month,
  to_date(cycle_key || '-01', 'YYYY-MM-DD') AS period_start,
  (to_date(cycle_key || '-01', 'YYYY-MM-DD') + interval '1 month - 1 day')::date AS period_end
FROM cycle_sources
WHERE cycle_key IS NOT NULL
ON CONFLICT (cycle_key) DO NOTHING;

UPDATE public.payments payment
SET monthly_cycle_id = cycle.id
FROM public.monthly_cycles cycle
WHERE payment.monthly_cycle_id IS NULL
  AND cycle.cycle_key = to_char(payment.period_end, 'YYYY-MM');

UPDATE public.onchain_payment_submissions submission
SET monthly_cycle_id = COALESCE(
  (SELECT payment.monthly_cycle_id FROM public.payments payment WHERE payment.id = submission.payment_id),
  submitted_cycle.id
)
FROM public.monthly_cycles submitted_cycle
WHERE submission.monthly_cycle_id IS NULL
  AND submitted_cycle.cycle_key = to_char(submission.submitted_at, 'YYYY-MM');

UPDATE public.project_stats_monthly stats
SET monthly_cycle_id = cycle.id
FROM public.monthly_cycles cycle
WHERE stats.monthly_cycle_id IS NULL
  AND stats.year IS NOT NULL
  AND stats.month BETWEEN 1 AND 12
  AND cycle.cycle_key = format('%s-%s', stats.year, lpad(stats.month::text, 2, '0'));

UPDATE public.zkas_identity_artifacts artifact
SET monthly_cycle_id = cycle.id
FROM public.monthly_cycles cycle
WHERE artifact.monthly_cycle_id IS NULL
  AND cycle.cycle_key = artifact.month;

UPDATE public.zkas_datasets dataset
SET monthly_cycle_id = cycle.id
FROM public.monthly_cycles cycle
WHERE dataset.monthly_cycle_id IS NULL
  AND cycle.cycle_key = dataset.month;

UPDATE public.zkas_runs run
SET monthly_cycle_id = cycle.id
FROM public.monthly_cycles cycle
WHERE run.monthly_cycle_id IS NULL
  AND cycle.cycle_key = run.month;

UPDATE public.zkas_run_payments run_payment
SET monthly_cycle_id = COALESCE(
  (SELECT payment.monthly_cycle_id FROM public.payments payment WHERE payment.id = run_payment.payment_id),
  cycle.id
)
FROM public.monthly_cycles cycle
WHERE run_payment.monthly_cycle_id IS NULL
  AND cycle.cycle_key = to_char(run_payment.period_end, 'YYYY-MM');

UPDATE public.zkas_run_attempts attempt
SET monthly_cycle_id = run.monthly_cycle_id
FROM public.zkas_runs run
WHERE attempt.monthly_cycle_id IS NULL
  AND run.id = attempt.run_id;

UPDATE public.zkas_run_results result
SET monthly_cycle_id = run.monthly_cycle_id
FROM public.zkas_runs run
WHERE result.monthly_cycle_id IS NULL
  AND run.id = result.run_id;

UPDATE public.zkas_published_user_results result
SET monthly_cycle_id = run.monthly_cycle_id
