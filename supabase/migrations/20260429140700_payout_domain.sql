CREATE POLICY payout_batch_items_self_select
ON public.payout_batch_items
FOR SELECT
USING (
  EXISTS (
    SELECT 1
    FROM public.payout_intents intent
    WHERE intent.id = payout_batch_items.payout_intent_id
      AND intent.user_id = auth.uid()
  )
);

