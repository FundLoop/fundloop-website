DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payout_rail') THEN
    CREATE TYPE public.payout_rail AS ENUM ('evm', 'solana', 'fiat_stub');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payout_route_status') THEN
    CREATE TYPE public.payout_route_status AS ENUM ('draft', 'active', 'disabled');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payout_intent_status') THEN
    CREATE TYPE public.payout_intent_status AS ENUM ('draft', 'ready', 'batched', 'processing', 'paid', 'failed', 'cancelled');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payout_batch_status') THEN
    CREATE TYPE public.payout_batch_status AS ENUM ('draft', 'ready', 'processing', 'completed', 'failed', 'cancelled');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payout_reconciliation_status') THEN
    CREATE TYPE public.payout_reconciliation_status AS ENUM ('pending', 'matched', 'mismatch', 'manual_review', 'resolved');
  END IF;
END
$$;

