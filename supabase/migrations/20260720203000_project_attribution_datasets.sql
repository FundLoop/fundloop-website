CREATE TABLE IF NOT EXISTS public.project_attribution_datasets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES public.projects(id) ON UPDATE CASCADE ON DELETE CASCADE,
  monthly_cycle_id bigint NOT NULL REFERENCES public.monthly_cycles(id) ON UPDATE CASCADE ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'submitted',
  row_count integer NOT NULL DEFAULT 0,
  total_attribution_points numeric(20, 6) NOT NULL DEFAULT 0,
  note text,
  proof_type text,
  proof_artifact_uri text,
  verifier_backend text,
  verification_status text,
  submitted_by_user_id uuid REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  submitted_at timestamp with time zone NOT NULL DEFAULT now(),
  approved_by_user_id uuid REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  approved_at timestamp with time zone,
  rejected_by_user_id uuid REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  rejected_at timestamp with time zone,
  rejection_reason text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT project_attribution_datasets_status_check CHECK (status IN ('draft', 'submitted', 'approved', 'rejected')),
  CONSTRAINT project_attribution_datasets_counts_check CHECK (row_count >= 0 AND total_attribution_points >= 0),
  CONSTRAINT project_attribution_datasets_proof_type_check CHECK (proof_type IS NULL OR proof_type IN ('raw_rows', 'zk_activity_sum')),
  CONSTRAINT project_attribution_datasets_verifier_backend_check CHECK (verifier_backend IS NULL OR verifier_backend IN ('tee', 'zk')),
  CONSTRAINT project_attribution_datasets_verification_status_check CHECK (
    verification_status IS NULL OR verification_status IN ('not_required', 'pending', 'verified', 'failed')
  ),
  CONSTRAINT project_attribution_datasets_current_key UNIQUE (project_id, monthly_cycle_id)
);

CREATE TABLE IF NOT EXISTS public.project_attribution_rows (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES public.project_attribution_datasets(id) ON UPDATE CASCADE ON DELETE CASCADE,
  project_id integer NOT NULL REFERENCES public.projects(id) ON UPDATE CASCADE ON DELETE CASCADE,
  monthly_cycle_id bigint NOT NULL REFERENCES public.monthly_cycles(id) ON UPDATE CASCADE ON DELETE CASCADE,
  row_index integer NOT NULL,
  scoped_cubid_id text NOT NULL,
  user_id uuid REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  user_email text,
  attribution_points numeric(20, 6) NOT NULL,
  category text,
  evidence_reference text,
  notes text,
  resolution_status text NOT NULL DEFAULT 'resolved',
  resolution_message text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT project_attribution_rows_points_check CHECK (attribution_points >= 0),
  CONSTRAINT project_attribution_rows_scoped_cubid_check CHECK (length(btrim(scoped_cubid_id)) > 0),
  CONSTRAINT project_attribution_rows_resolution_status_check CHECK (resolution_status IN ('resolved', 'unresolved')),
  CONSTRAINT project_attribution_rows_dataset_index_key UNIQUE (dataset_id, row_index)
);

CREATE INDEX IF NOT EXISTS idx_project_attribution_datasets_cycle
ON public.project_attribution_datasets (monthly_cycle_id, project_id, status);

CREATE INDEX IF NOT EXISTS idx_project_attribution_datasets_project
ON public.project_attribution_datasets (project_id, submitted_at DESC);

CREATE INDEX IF NOT EXISTS idx_project_attribution_rows_dataset
ON public.project_attribution_rows (dataset_id, row_index);

CREATE INDEX IF NOT EXISTS idx_project_attribution_rows_cycle_user
ON public.project_attribution_rows (monthly_cycle_id, user_id);

CREATE INDEX IF NOT EXISTS idx_project_attribution_rows_scoped_cubid
ON public.project_attribution_rows (scoped_cubid_id);

DROP TRIGGER IF EXISTS set_project_attribution_datasets_updated_at ON public.project_attribution_datasets;
CREATE TRIGGER set_project_attribution_datasets_updated_at
BEFORE UPDATE ON public.project_attribution_datasets
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

ALTER TABLE public.project_attribution_datasets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.project_attribution_rows ENABLE ROW LEVEL SECURITY;
