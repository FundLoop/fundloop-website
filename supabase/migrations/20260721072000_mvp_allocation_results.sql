CREATE TABLE IF NOT EXISTS public.monthly_cycle_allocation_project_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monthly_cycle_id bigint NOT NULL REFERENCES public.monthly_cycles(id) ON UPDATE CASCADE ON DELETE CASCADE,
  run_id bigint NOT NULL REFERENCES public.zkas_runs(id) ON UPDATE CASCADE ON DELETE CASCADE,
  project_id integer NOT NULL REFERENCES public.projects(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  user_id uuid NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  scoped_cubid_id text NOT NULL,
  attribution_points numeric(20, 6) NOT NULL,
  total_project_points numeric(20, 6) NOT NULL,
  project_pool_usd numeric(20, 6) NOT NULL,
  raw_usd numeric(20, 6) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT monthly_cycle_allocation_project_results_run_project_user_key UNIQUE (run_id, project_id, user_id),
  CONSTRAINT monthly_cycle_allocation_project_results_amounts_check CHECK (
    attribution_points >= 0
    AND total_project_points >= 0
    AND project_pool_usd >= 0
    AND raw_usd >= 0
  )
);

CREATE INDEX IF NOT EXISTS idx_monthly_cycle_allocation_project_results_cycle
ON public.monthly_cycle_allocation_project_results (monthly_cycle_id, project_id, raw_usd DESC);

CREATE INDEX IF NOT EXISTS idx_monthly_cycle_allocation_project_results_run
ON public.monthly_cycle_allocation_project_results (run_id, user_id);

CREATE TABLE IF NOT EXISTS public.monthly_cycle_allocation_asset_fills (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monthly_cycle_id bigint NOT NULL REFERENCES public.monthly_cycles(id) ON UPDATE CASCADE ON DELETE CASCADE,
  run_id bigint NOT NULL REFERENCES public.zkas_runs(id) ON UPDATE CASCADE ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES public.users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  pool_id text NOT NULL,
  project_id integer NOT NULL REFERENCES public.projects(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  asset_type text NOT NULL,
  asset_code text NOT NULL,
  source_amount numeric(20, 6) NOT NULL,
  usd_value numeric(20, 6) NOT NULL,
  preference_rank integer NOT NULL,
  partial boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT monthly_cycle_allocation_asset_fills_type_check CHECK (asset_type IN ('project_token', 'stablecoin', 'fiat')),
  CONSTRAINT monthly_cycle_allocation_asset_fills_amounts_check CHECK (source_amount >= 0 AND usd_value >= 0)
);

CREATE INDEX IF NOT EXISTS idx_monthly_cycle_allocation_asset_fills_cycle
ON public.monthly_cycle_allocation_asset_fills (monthly_cycle_id, asset_type, asset_code);

CREATE INDEX IF NOT EXISTS idx_monthly_cycle_allocation_asset_fills_run
ON public.monthly_cycle_allocation_asset_fills (run_id, user_id);

CREATE TABLE IF NOT EXISTS public.monthly_cycle_allocation_returned_pools (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monthly_cycle_id bigint NOT NULL REFERENCES public.monthly_cycles(id) ON UPDATE CASCADE ON DELETE CASCADE,
  run_id bigint NOT NULL REFERENCES public.zkas_runs(id) ON UPDATE CASCADE ON DELETE CASCADE,
  pool_id text NOT NULL,
  project_id integer NOT NULL REFERENCES public.projects(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  asset_type text NOT NULL,
  asset_code text NOT NULL,
  source_amount numeric(20, 6) NOT NULL,
  usd_value numeric(20, 6) NOT NULL,
  reason_code text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT monthly_cycle_allocation_returned_pools_type_check CHECK (asset_type IN ('project_token', 'stablecoin', 'fiat')),
  CONSTRAINT monthly_cycle_allocation_returned_pools_reason_check CHECK (
    reason_code IN ('no_eligible_attribution', 'cap_remainder', 'preference_unfulfillable', 'rounding_remainder')
  ),
  CONSTRAINT monthly_cycle_allocation_returned_pools_amounts_check CHECK (source_amount >= 0 AND usd_value >= 0)
);

CREATE INDEX IF NOT EXISTS idx_monthly_cycle_allocation_returned_pools_cycle
ON public.monthly_cycle_allocation_returned_pools (monthly_cycle_id, project_id, reason_code);

CREATE INDEX IF NOT EXISTS idx_monthly_cycle_allocation_returned_pools_run
ON public.monthly_cycle_allocation_returned_pools (run_id, project_id);

ALTER TABLE public.monthly_cycle_allocation_project_results ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.monthly_cycle_allocation_asset_fills ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.monthly_cycle_allocation_returned_pools ENABLE ROW LEVEL SECURITY;
